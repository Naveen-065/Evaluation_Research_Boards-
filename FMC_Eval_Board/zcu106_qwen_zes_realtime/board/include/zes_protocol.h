#ifndef ZES_PROTOCOL_H
#define ZES_PROTOCOL_H

#include <stdint.h>

#define ZES_PROTOCOL_MAGIC "ZES1"
#define ZES_PROTOCOL_MAGIC_SIZE 4u
#define ZES_PROTOCOL_VERSION 1u
#define ZES_PROTOCOL_HEADER_SIZE 16u
#define ZES_PROTOCOL_MAX_PAYLOAD 4096u

#define ZES_DATA_BYTES 1024u
#define ZES_PARITY_BYTES 72u
#define ZES_DATA_WORDS 256u
#define ZES_PARITY_WORDS 18u

enum zes_opcode {
    ZES_OP_INFO = 0x01,
    ZES_OP_ENCODE = 0x02,
    ZES_OP_CHECK_REPAIR = 0x03
};

#define ZES_RESPONSE_BIT 0x80u

enum zes_status {
    ZES_STATUS_OK = 0,
    ZES_STATUS_BAD_MAGIC = 1,
    ZES_STATUS_BAD_VERSION = 2,
    ZES_STATUS_BAD_OPCODE = 3,
    ZES_STATUS_BAD_LENGTH = 4,
    ZES_STATUS_BAD_ARGUMENT = 5,
    ZES_STATUS_LIBRARY_GEOMETRY = 6,
    ZES_STATUS_INTERNAL = 7
};

#endif
